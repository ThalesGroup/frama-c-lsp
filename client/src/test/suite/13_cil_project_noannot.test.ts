import * as assert from 'assert';
import * as vscode from 'vscode';
import * as path from 'path';
import * as fs from 'fs';
import { openBenchmark, activateExtension, cleanFile, getWorkspacePath } from './helpers';

suite('displayCILProject_noannot', () => {

    test('generates project CIL without ACSL annotations', async function() {
        this.timeout(120000);

        // same config as displayCILProject — kernel.sourceFiles points to
        // global_metrics/main.c and utils.c via benchmarks/.vscode/settings.json
        await openBenchmark('global_metrics/main.c');
        await activateExtension();

        const outFile = path.join(getWorkspacePath(), '.frama-c', 'fc_project.c');
        cleanFile(outFile);

        await vscode.commands.executeCommand('displayCILProject_noannot');

        // manual poll — file starts with "Task in progress" then gets overwritten by frama-c
        const start = Date.now();
        let cil = '';
        while (Date.now() - start < 90000) {
            if (fs.existsSync(outFile)) {
                const content = fs.readFileSync(outFile, 'utf-8');
                if (content.length > 0 && !content.startsWith('Task in progress')) {
                    cil = content;
                    break;
                }
            }
            await new Promise(r => setTimeout(r, 1000));
        }

        console.log(`fc_project.c (noannot) size: ${cil.length} chars`);
        console.log(cil.substring(0, 300));

        assert.ok(cil.length > 0, 'fc_project.c is empty or missing');
        assert.ok(cil.includes('/* Generated by Frama-C */'), 'Frama-C header missing');
        assert.ok(cil.includes('add'),     'function add missing from project CIL');
        assert.ok(cil.includes('compute'), 'function compute missing from project CIL');

        // no ACSL annotations
        assert.ok(!cil.includes('/*@'),      'ACSL annotations present — noannot not applied');
        assert.ok(!cil.includes('requires'), 'requires present — noannot not applied');
        assert.ok(!cil.includes('ensures'),  'ensures present — noannot not applied');
        assert.ok(!cil.includes('assigns'),  'assigns present — noannot not applied');
    });
});